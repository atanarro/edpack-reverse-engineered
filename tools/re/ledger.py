"""Writes docs/validation.md: every function of the original interpreters, whether the Rust
code says it ports it, and whether tests/oracle.rs checks it against the original.

    python tools/re/ledger.py
"""

import os
import re

from image import Image

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
SRC = {'rundat': ['src'], 'runvga': ['src/v1']}


def cited(prog):
    """{address: ['file:line description']} from "(0xNNNN)" mentions in the Rust sources.
    v2 files are those outside src/v1."""
    out = {}
    for base in SRC[prog]:
        for dirpath, _, files in os.walk(os.path.join(ROOT, base)):
            if prog == 'rundat' and os.path.basename(dirpath) == 'v1':
                continue
            for f in files:
                if not f.endswith('.rs'):
                    continue
                path = os.path.join(dirpath, f)
                rel = os.path.relpath(path, ROOT)
                if prog == 'rundat' and rel.startswith('src/compiler'):
                    continue  # the compiler cites ED.EXE, not RUNDAT.EXE
                for n, line in enumerate(open(path, encoding='utf-8'), 1):
                    if '//' not in line:
                        continue
                    text = line[line.index('//'):].lstrip('/!').strip()
                    for m in re.finditer(r'\(0x([0-9a-f]{3,5})\)', text):
                        out.setdefault(int(m.group(1), 16), []).append(f'`{rel}:{n}` {text[:70]}')
    return out


def tested(prog):
    """{address: (cases, coverage)} for the functions tests/oracle.rs checks."""
    test = open(os.path.join(ROOT, 'tests', 'oracle.rs')).read()
    out = {}
    for m in re.finditer(rf'check\("{prog}_([0-9a-f]+)"', test):
        a = int(m.group(1), 16)
        vec = os.path.join(ROOT, 'tests', 'oracle', f'{prog}_{a:04x}.vec')
        cases, cov = '?', '?'
        if os.path.exists(vec):
            text = open(vec).read()
            cases = text.count('\ncase')
            cov = re.search(r'coverage (\S+)', text).group(1)
        out[a] = (cases, cov)
    return out


def main():
    lines = ['# Validation against the original binaries', '',
             'Generated by `tools/re/ledger.py`; see `tools/re/README.md` for the method.', '',
             '*Function* = a near-call target found by recursive disassembly from the entry point',
             '(and, for RUNDAT, the bytecode jump table). *Cited* = the Rust code names the address.',
             '*Differential* = `tests/oracle.rs` replays the original\'s behaviour on fuzzed inputs',
             'and requires the Rust port to produce the same data-segment bytes.', '']
    # The v1 port cites RUNVGA v1.03 (Manolo Kabezabolo's runtime); games/ only has the v1.0
    # demo's RUNVGA, whose addresses differ, so v1 is left out until that binary is added.
    for prog in ('rundat',):
        img = Image(prog)
        funcs = img.functions()
        cit, tst = cited(prog), tested(prog)
        n_cited = sum(1 for a in cit if a in funcs)
        lines += [f'## {prog.upper()}.EXE', '',
                  f'{len(funcs)} functions; {n_cited} cited by the Rust code; '
                  f'{sum(1 for a in tst if a in funcs)} checked differentially.', '',
                  '| Address | Size | Status | Rust |', '|---|---|---|---|']
        for a in sorted(set(cit) | set(tst)):
            size = len(img.listing(a)) if a in funcs or a < img.code_size else 0
            if a in tst:
                status = f'differential: {tst[a][0]} cases, {tst[a][1]} insns covered'
            else:
                status = 'cited, not checked'
            if a not in funcs:
                status += ' (not a call target: inner block or indirect call)'
            lines.append(f'| `{a:04x}` | {size} | {status} | {"<br>".join(cit.get(a, ["—"]))} |')
        lines += ['', f'Functions not cited anywhere ({len(funcs) - n_cited}, mostly the Borland C '
                  'run-time library and helpers inlined into a cited function\'s port):', '',
                  ' '.join(f'`{a:04x}`' for a in sorted(funcs) if a not in cit), '']
    out = os.path.join(ROOT, 'docs', 'validation.md')
    open(out, 'w').write('\n'.join(lines))
    print('wrote', os.path.relpath(out))


if __name__ == '__main__':
    main()
